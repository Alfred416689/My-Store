create table if not exists public.products (
  id integer generated by default as identity primary key,
  name text not null,
  price integer not null check (price > 0),
  compare_at_price integer check (compare_at_price is null or compare_at_price > price),
  category text not null,
  collections text[] not null default array['everyday']::text[],
  featured boolean not null default false,
  condition text not null,
  sizes text[] not null default '{}',
  image text not null,
  gallery text[] not null default '{}',
  image_path text,
  description text not null,
  stock integer not null default 0 check (stock >= 0),
  badge text,
  constraint products_collections_valid check (
    cardinality(collections) > 0 and collections <@ array['everyday', 'curated']::text[]
  )
);

create index if not exists products_price_id_idx on public.products (price, id);
create index if not exists products_name_idx on public.products (name);
create index if not exists products_category_idx on public.products (category);
create index if not exists products_collections_gin_idx
  on public.products using gin (collections);

create table if not exists public.customer_requests (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null,
  brand text not null default '',
  size text not null default '',
  colour text not null default '',
  budget integer not null check (budget > 0),
  details text not null default '',
  status text not null default 'Pending' check (status in ('Pending', 'Approved')),
  requested_at timestamptz not null default now(),
  approved_at timestamptz,
  approved_by text,
  image_path text
);

create index if not exists customer_requests_status_requested_at_idx
  on public.customer_requests (status, requested_at desc);

create table if not exists public.newsletter_subscribers (
  email_normalized text primary key,
  email text not null,
  subscribed_at timestamptz not null default now()
);

create table if not exists public.shopping_carts (
  session_id text primary key,
  items jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists shopping_carts_expires_at_idx
  on public.shopping_carts (expires_at);

create or replace function public.prune_expired_shopping_carts()
returns integer
language sql
security definer
set search_path = ''
as $$
  with expired as (
    select session_id
    from public.shopping_carts
    where expires_at <= now()
    order by expires_at
    limit 1000
  ),
  deleted as (
    delete from public.shopping_carts as carts
    using expired
    where carts.session_id = expired.session_id
    returning 1
  )
  select count(*)::integer from deleted;
$$;

alter table public.products enable row level security;
alter table public.customer_requests enable row level security;
alter table public.newsletter_subscribers enable row level security;
alter table public.shopping_carts enable row level security;

grant all on table public.products to service_role;
grant all on table public.customer_requests to service_role;
grant all on table public.newsletter_subscribers to service_role;
grant all on table public.shopping_carts to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on function public.prune_expired_shopping_carts() from public, anon, authenticated;
grant execute on function public.prune_expired_shopping_carts() to service_role;

